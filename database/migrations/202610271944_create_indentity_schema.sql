CREATE TABLE public.users (
    id uuid PRIMARY KEY,
    user_name varchar(256) NOT NULL,
    normalized_user_name varchar(256) NOT NULL,
    email varchar(256) NOT NULL,
    normalized_email varchar(256) NOT NULL,
    email_confirmed boolean NOT NULL DEFAULT false,
    password_hash text,
    security_stamp text,
    concurrency_stamp text,
    phone_number text,
    phone_number_confirmed boolean NOT NULL DEFAULT false,
    two_factor_enabled boolean NOT NULL DEFAULT false,
    lockout_end timestamptz,
    lockout_enabled boolean NOT NULL DEFAULT true,
    access_failed_count integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_users_user_name_not_empty
        CHECK (btrim(user_name) <> ''),
    CONSTRAINT ck_users_normalized_user_name_not_empty
        CHECK (btrim(normalized_user_name) <> ''),
    CONSTRAINT ck_users_email_not_empty
        CHECK (btrim(email) <> ''),
    CONSTRAINT ck_users_normalized_email_not_empty
        CHECK (btrim(normalized_email) <> ''),
    CONSTRAINT ck_users_access_failed_count
        CHECK (access_failed_count >= 0),
    CONSTRAINT ck_users_updated_at
        CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX ux_users_normalized_user_name
    ON public.users (normalized_user_name);

CREATE UNIQUE INDEX ux_users_normalized_email
    ON public.users (normalized_email);


CREATE TABLE public.user_claims (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    claim_type text,
    claim_value text,

    CONSTRAINT fk_user_claims_user
        FOREIGN KEY (user_id)
        REFERENCES public.users (id)
        ON DELETE CASCADE
);

CREATE INDEX ix_user_claims_user_id
    ON public.user_claims (user_id);


