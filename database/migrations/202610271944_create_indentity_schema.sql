CREATE TABLE public.refresh_tokens (
    id uuid PRIMARY KEY,
    user_id uuid NOT NULL,
    family_id uuid NOT NULL,
    token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    revoked_at timestamptz,
    replaced_by_token_id uuid,
    device_name varchar(200),
    user_agent text,
    ip_address inet,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id)
        REFERENCES public.users (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_replacement
        FOREIGN KEY (replaced_by_token_id)
        REFERENCES public.refresh_tokens (id)
        ON DELETE SET NULL,
    CONSTRAINT ck_refresh_tokens_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_tokens_expiry
        CHECK (expires_at > created_at),
    CONSTRAINT ck_refresh_tokens_not_self_replaced
        CHECK (
            replaced_by_token_id IS NULL
            OR replaced_by_token_id <> id
        )
);

CREATE UNIQUE INDEX ux_refresh_tokens_token_hash
    ON public.refresh_tokens (token_hash);

CREATE INDEX ix_refresh_tokens_user_id
    ON public.refresh_tokens (user_id);

CREATE INDEX ix_refresh_tokens_family_id
    ON public.refresh_tokens (family_id);

CREATE INDEX ix_refresh_tokens_expires_at
    ON public.refresh_tokens (expires_at);


